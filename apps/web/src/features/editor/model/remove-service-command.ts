import {
  applyGraphCommand,
  getArchitectureDocumentHashes,
  type ArchitectureDocument,
  type ArchitectureDocumentHashes,
} from "@cloudmarkup/domain";
import type { ProviderConnectionResolverV1 } from "@cloudmarkup/provider-sdk";
import {
  parseGraphCommandV1,
  type GraphCommandActionV1,
  type GraphCommandV1,
} from "@cloudmarkup/schemas";

export interface PreparedServiceRemoval {
  readonly beforeHashes: ArchitectureDocumentHashes;
  readonly command: GraphCommandV1;
  readonly connectionCount: number;
  readonly label: string;
  readonly nodeId: string;
  readonly previewHashes: ArchitectureDocumentHashes;
  readonly releasedResourceCount: number;
}

export class ServiceRemovalError extends Error {
  public constructor(message: string) {
    super(message);
    this.name = "ServiceRemovalError";
  }
}

/** Prepare a single atomic removal; the caller must replay this exact preview. */
export function prepareServiceRemoval(input: {
  readonly connectionResolver?: ProviderConnectionResolverV1;
  readonly createId: () => string;
  readonly document: ArchitectureDocument;
  readonly nodeId: string;
}): PreparedServiceRemoval {
  const { document, nodeId, createId } = input;
  const node = document.nodes.find((candidate) => candidate.id === nodeId);
  if (node === undefined)
    throw new ServiceRemovalError("This service is no longer in the design.");
  if (node.semantic.lifecycle.ownership === "generated")
    throw new ServiceRemovalError(
      "This service is generated by another resource. Remove its owning connection through its reviewed workflow first.",
    );
  if (
    document.nodes.some(
      (candidate) => candidate.semantic.parent?.nodeId === nodeId,
    )
  )
    throw new ServiceRemovalError(
      "Move or remove services inside this boundary before deleting it.",
    );

  const incidentEdges = document.edges
    .filter(
      (edge) =>
        edge.semantic.source.nodeId === nodeId ||
        edge.semantic.target.nodeId === nodeId,
    )
    .sort((left, right) =>
      left.id < right.id ? -1 : left.id > right.id ? 1 : 0,
    );
  const actions: GraphCommandActionV1[] = [];
  let working = document;
  let releasedResourceCount = 0;
  const target = {
    architectureId: document.architectureId,
    documentId: document.documentId,
    revisionId: document.revision.revisionId,
  };
  const operation = (
    payload: Record<string, unknown>,
  ): GraphCommandActionV1 => {
    const command = parseGraphCommandV1({
      schemaVersion: 1,
      commandId: createId(),
      inverseCommandId: createId(),
      origin: "user",
      target,
      ...payload,
    });
    if (command.kind === "batch")
      throw new ServiceRemovalError("Expected one removal action.");
    return command;
  };

  for (const [index, edge] of incidentEdges.entries()) {
    if (!working.edges.some((candidate) => candidate.id === edge.id)) continue;
    if (edge.semantic.lifecycle.ownership === "adopted")
      throw new ServiceRemovalError(
        "A customized connection uses this service. Review and disconnect it before deleting the service.",
      );
    if (edge.semantic.lifecycle.ownership === "generated") {
      // Resolver operation IDs are short seeds; createId supplies uniqueness across previews.
      const seed = createId()
        .replace(/[^a-z0-9]/gu, "_")
        .slice(-18);
      if (input.connectionResolver === undefined)
        throw new ServiceRemovalError(
          "A generated connection uses this service. Open it with its exact connection catalog before deleting.",
        );
      const cleanup = input.connectionResolver.cleanup({
        connectionEdgeId: edge.id,
        document: working,
        operationId: `remove_${seed}_${String(index)}`,
      });
      if (!cleanup.success)
        throw new ServiceRemovalError(
          cleanup.findings[0]?.guidedMessage ??
            "This generated connection cannot be removed safely yet.",
        );
      if (
        cleanup.preview.changes.some(
          (change) =>
            change.kind === "generated-resource-released" &&
            change.disposition === "retained",
        )
      )
        throw new ServiceRemovalError(
          "A generated connection shares resources with another service. Review those dependencies before deleting this service.",
        );
      actions.push(...cleanup.batch.commands);
      releasedResourceCount += cleanup.batch.commands.filter(
        (command) => command.kind === "release-generated-resource",
      ).length;
      working = cleanup.preview.document;
      continue;
    }
    actions.push(
      operation({ kind: "remove-edge", edgeId: edge.id, expectedEdge: edge }),
    );
  }
  actions.push(operation({ kind: "remove-node", nodeId, expectedNode: node }));
  const command = parseGraphCommandV1({
    schemaVersion: 1,
    commandId: createId(),
    inverseCommandId: createId(),
    origin: "user",
    target,
    kind: "batch",
    commands: actions,
  });
  try {
    const result = applyGraphCommand(document, command);
    if (result.inversion.kind !== "available")
      throw new ServiceRemovalError(
        "The connected resources cannot be safely restored by Undo. Review their dependencies first.",
      );
    return {
      beforeHashes: getArchitectureDocumentHashes(document),
      command,
      connectionCount: incidentEdges.length,
      label: `Delete ${node.presentation.label}`,
      nodeId,
      previewHashes: getArchitectureDocumentHashes(result.document),
      releasedResourceCount,
    };
  } catch (error) {
    if (error instanceof ServiceRemovalError) throw error;
    throw new ServiceRemovalError(
      "This service is still referenced by the design, an output, or application behavior. Remove those references before deleting it.",
    );
  }
}
